-- TrendzzNow safe Supabase setup / migration
-- IMPORTANT:
-- 1) This script intentionally does NOT DROP or truncate existing tables.
-- 2) The Express server must use the Supabase service_role key only on the server.
-- 3) Never put SUPABASE_KEY/service_role credentials in browser JavaScript or GitHub.

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  title text not null,
  category text default 'Trending',
  price numeric not null,
  regular_price numeric,
  cost_price numeric default 0,
  stock_quantity integer default 50,
  description text,
  image text,
  variant_options text,
  created_at timestamptz not null default now()
);

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  product_id bigint references public.products(id) on delete set null,
  customer_name text not null,
  phone text not null,
  customer_email text,
  address text not null,
  product_title text not null,
  unit_price numeric,
  delivery_charge numeric default 0,
  discount_applied numeric default 0,
  price numeric not null,
  quantity integer default 1,
  status text default 'Pending',
  consignment_id text default '',
  admin_notes text default '',
  created_at timestamptz not null default now()
);

create table if not exists public.settings (
  key text primary key,
  value text
);

-- Add newer fields to existing v21 tables without destroying current data.
alter table public.orders add column if not exists product_id bigint references public.products(id) on delete set null;
alter table public.orders add column if not exists unit_price numeric;
alter table public.orders add column if not exists delivery_charge numeric default 0;
alter table public.orders add column if not exists discount_applied numeric default 0;
alter table public.products add column if not exists variant_options text;
alter table public.products add column if not exists stock_quantity integer default 50;

create index if not exists idx_products_created_at on public.products (created_at desc);
create index if not exists idx_products_category on public.products (category);
create index if not exists idx_orders_phone_id on public.orders (phone, id desc);
create index if not exists idx_orders_created_at on public.orders (created_at desc);

-- Browser/anon roles must not query customer/order tables directly.
-- The Node server uses the server-only service_role key and performs authorization.
alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.settings enable row level security;

-- Product pictures are public storefront assets. Uploads are performed by the server
-- using the service_role key, not by exposing credentials in the customer interface.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'product-images',
  'product-images',
  true,
  5242880,
  array['image/jpeg', 'image/png', 'image/webp', 'image/gif']
)
on conflict (id) do update set
  public = excluded.public,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

notify pgrst, 'reload schema';
