-- Add it before creating idx_products_category below; this is safe for existing rows.
alter table public.products add column if not exists category text default 'Trending';
alter table public.products add column if not exists variant_options text;
alter table public.products add column if not exists stock_quantity integer default 50;
alter table public.products add column if not exists sku text;
alter table public.products add column if not exists low_stock_threshold integer default 5;
alter table public.products add column if not exists is_active boolean default true;
alter table public.orders add column if not exists stock_reserved boolean not null default false;
alter table public.orders add column if not exists stock_released boolean not null default false;

-- Inventory movement history and administrator audit trail are additive tables.
create table if not exists public.inventory_movements (
  id bigint generated by default as identity primary key,
  product_id bigint references public.products(id) on delete set null,
  product_title text not null,
  movement_type text not null,
  quantity_change integer not null default 0,
  previous_quantity integer not null default 0,
  new_quantity integer not null default 0,
  reason text default '',
  reference text default '',
  created_at timestamptz not null default now()
);

create table if not exists public.admin_audit_logs (
  id bigint generated by default as identity primary key,
  actor text not null default 'store_admin',
  action text not null,
  entity_type text not null,
  entity_id text default '',
  details jsonb not null default '{}'::jsonb,
  ip_address text default '',
  created_at timestamptz not null default now()
);

create index if not exists idx_products_created_at on public.products (created_at desc);
create index if not exists idx_products_category on public.products (category);
create index if not exists idx_orders_phone_id on public.orders (phone, id desc);
create index if not exists idx_orders_created_at on public.orders (created_at desc);
create index if not exists idx_inventory_movements_product on public.inventory_movements (product_id, created_at desc);
create index if not exists idx_inventory_movements_created_at on public.inventory_movements (created_at desc);
create index if not exists idx_admin_audit_logs_created_at on public.admin_audit_logs (created_at desc);


-- Reserve order stock in one database transaction after the order row has been
-- created. The product row lock prevents two customers from buying the same last unit.
create or replace function public.trendzznow_reserve_order_stock(p_order_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $function$
declare
  v_order public.orders%rowtype;
  v_product public.products%rowtype;
  v_qty integer;
  v_previous integer;
  v_next integer;
begin
  select * into v_order from public.orders where id = p_order_id for update;
  if not found then raise exception 'Order not found.'; end if;
  if v_order.status <> 'Pending' or coalesce(v_order.stock_reserved, false) then
    raise exception 'Order stock is already reserved or order is not pending.';
  end if;
  if v_order.product_id is null then raise exception 'Order has no linked product.'; end if;

  select * into v_product from public.products where id = v_order.product_id for update;
  if not found or v_product.is_active is false then raise exception 'Product is no longer available.'; end if;
  if v_order.unit_price is null or v_product.price is distinct from v_order.unit_price then
    raise exception 'Product price changed. Refresh the page and place the order again.';
  end if;

  v_qty := greatest(coalesce(v_order.quantity, 1), 1);
  if v_product.stock_quantity is null or v_product.stock_quantity < v_qty then
    raise exception 'There is not enough stock for this order.';
  end if;

  v_previous := v_product.stock_quantity;
  v_next := v_previous - v_qty;
  update public.products set stock_quantity = v_next where id = v_product.id;
  update public.orders set stock_reserved = true, stock_released = false where id = p_order_id;
  insert into public.inventory_movements
    (product_id, product_title, movement_type, quantity_change, previous_quantity, new_quantity, reason, reference)
  values
    (v_product.id, v_product.title, 'order_reserved', -v_qty, v_previous, v_next,
     'Customer order placed', p_order_id::text);

  return jsonb_build_object('success', true, 'order_id', p_order_id,
                            'previous_stock', v_previous, 'new_stock', v_next, 'quantity', v_qty);
end;
$function$;

-- Stock-aware order transitions. These functions run as SECURITY DEFINER but
-- execution is granted only to Supabase service_role (never anon/authenticated).
create or replace function public.trendzznow_update_order_status(
  p_order_id bigint,
  p_new_status text,
  p_consignment_id text default null,
  p_admin_notes text default null
) returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $function$
declare
  v_order public.orders%rowtype;
  v_product public.products%rowtype;
  v_qty integer;
  v_previous integer;
  v_next integer;
begin
  if p_new_status not in ('Pending', 'Confirmed', 'Sent to SteadFast', 'Sent to Pathao', 'Delivered', 'Cancelled', 'Return') then
    raise exception 'Invalid order status.';
  end if;

  select * into v_order from public.orders where id = p_order_id for update;
  if not found then raise exception 'Order not found.'; end if;
  v_qty := greatest(coalesce(v_order.quantity, 1), 1);

  -- Restore stock only for a cancellation before courier dispatch. Shipped or
  -- delivered returns require a human inspection and manual stock adjustment.
  if coalesce(v_order.stock_reserved, false)
     and not coalesce(v_order.stock_released, false)
     and p_new_status = 'Cancelled'
     and v_order.status in ('Pending', 'Confirmed')
     and v_order.product_id is not null then
    select * into v_product from public.products where id = v_order.product_id for update;
    if found then
      v_previous := coalesce(v_product.stock_quantity, 0);
      v_next := v_previous + v_qty;
      update public.products set stock_quantity = v_next where id = v_product.id;
      insert into public.inventory_movements
        (product_id, product_title, movement_type, quantity_change, previous_quantity, new_quantity, reason, reference)
      values
        (v_product.id, v_product.title, 'order_cancelled_restore', v_qty, v_previous, v_next,
         'Stock returned for cancellation before dispatch', p_order_id::text);
      v_order.stock_released := true;
    end if;
  elsif coalesce(v_order.stock_reserved, false)
     and coalesce(v_order.stock_released, false)
     and v_order.status in ('Cancelled', 'Return')
     and p_new_status not in ('Cancelled', 'Return')
     and v_order.product_id is not null then
    select * into v_product from public.products where id = v_order.product_id for update;
    if found then
      if v_product.stock_quantity is null or v_product.stock_quantity < v_qty then
        raise exception 'Not enough stock to reactivate this cancelled order.';
      end if;
      v_previous := v_product.stock_quantity;
      v_next := v_previous - v_qty;
      update public.products set stock_quantity = v_next where id = v_product.id;
      insert into public.inventory_movements
        (product_id, product_title, movement_type, quantity_change, previous_quantity, new_quantity, reason, reference)
      values
        (v_product.id, v_product.title, 'cancelled_order_reactivated', -v_qty, v_previous, v_next,
         'Stock reserved again after order reactivation', p_order_id::text);
      v_order.stock_released := false;
    end if;
  end if;

  update public.orders
     set status = p_new_status,
         consignment_id = coalesce(p_consignment_id, consignment_id),
         admin_notes = coalesce(p_admin_notes, admin_notes),
         stock_released = coalesce(v_order.stock_released, false)
   where id = p_order_id;

  return jsonb_build_object('success', true, 'order_id', p_order_id, 'status', p_new_status,
                            'stock_reserved', coalesce(v_order.stock_reserved, false),
                            'stock_released', coalesce(v_order.stock_released, false));
end;
$function$;

create or replace function public.trendzznow_delete_order_restore_stock(p_order_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $function$
declare
  v_order public.orders%rowtype;
  v_product public.products%rowtype;
  v_qty integer;
  v_previous integer;
  v_next integer;
begin
  select * into v_order from public.orders where id = p_order_id for update;
  if not found then raise exception 'Order not found.'; end if;
  if v_order.status not in ('Pending', 'Confirmed') then
    raise exception 'Dispatched, delivered or returned orders are retained for fulfilment history and cannot be deleted.';
  end if;
  v_qty := greatest(coalesce(v_order.quantity, 1), 1);

  if coalesce(v_order.stock_reserved, false)
     and not coalesce(v_order.stock_released, false)
     and v_order.status in ('Pending', 'Confirmed')
     and v_order.product_id is not null then
    select * into v_product from public.products where id = v_order.product_id for update;
    if found then
      v_previous := coalesce(v_product.stock_quantity, 0);
      v_next := v_previous + v_qty;
      update public.products set stock_quantity = v_next where id = v_product.id;
      insert into public.inventory_movements
        (product_id, product_title, movement_type, quantity_change, previous_quantity, new_quantity, reason, reference)
      values
        (v_product.id, v_product.title, 'order_deleted_restore', v_qty, v_previous, v_next,
         'Stock returned when a pending order was deleted', p_order_id::text);
    end if;
  end if;

  delete from public.orders where id = p_order_id;
  return jsonb_build_object('success', true, 'deleted_order_id', p_order_id);
end;
$function$;

