export const DICTS = { bn, en };

function initial() {
  try {
    const l = localStorage.getItem('tn_lang');
    if (l === 'bn' || l === 'en') return l;
  } catch (e) {
    /* storage blocked */
  }
  const boot = typeof window !== 'undefined' && window.__BOOT__ && window.__BOOT__.settings;
  return boot && boot.defaultLang === 'en' ? 'en' : 'bn';
}

let lang = initial();

export const getLang = () => lang;
export function setLangState(l) {
  if (DICTS[l]) lang = l;
}

export function t(key, params) {
  let s = DICTS[lang][key];
  if (s == null) s = DICTS.bn[key];
  if (s == null) s = key;
  if (params) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in params ? params[k] : m));
  return s;
}
